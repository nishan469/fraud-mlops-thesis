def esc_rows(rows, head=True, cls=""):
    out = [f'<table class="{cls}">']
    if head:
        out.append("<thead><tr>" + "".join(f"<th>{c}</th>" for c in rows[0]) + "</tr></thead>")
        rows = rows[1:]
    out.append("<tbody>" + "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
                                   for r in rows) + "</tbody></table>")
    return "".join(out)


